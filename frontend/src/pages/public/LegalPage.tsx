export function LegalPage() {
  const { slug } = useParams<{ slug: string }>()

  const staticPage = slug ? staticPages[slug] : null

  const { data: cmsPage, isLoading } = useQuery({
    queryKey: ['cms-page', slug],
    queryFn: () => api.getPage(slug!),
    enabled: !!slug && !staticPage,
  })

  const page = staticPage || cmsPage

  if (isLoading && !staticPage) {
    return (
      <div className="max-w-4xl mx-auto px-4 py-8 space-y-4">
        <Skeleton height={40} width="50%" />
        <Skeleton height={20} width="100%" />
        <Skeleton height={20} width="90%" />
        <Skeleton height={20} width="95%" />
      </div>
    )
  }

  if (!page) {
    return (
      <div className="max-w-4xl mx-auto px-4 py-16 text-center">
        <h1 className="text-2xl font-bold text-gray-100 mb-2">Страница не найдена</h1>
        <p className="text-gray-400">Запрашиваемая страница не существует</p>
      </div>
    )
  }

  return (
    <div className="max-w-4xl mx-auto px-4 py-8">
      <h1 className="text-3xl font-bold text-gray-100 mb-6">{page.title}</h1>
      <div
        className="prose prose-invert prose-sm max-w-none
          [&_h2]:text-xl [&_h2]:font-semibold [&_h2]:text-gray-100 [&_h2]:mt-8 [&_h2]:mb-3
          [&_p]:text-gray-400 [&_p]:leading-relaxed [&_p]:mb-3
          [&_strong]:text-gray-200
          [&_ul]:list-disc [&_ul]:pl-5 [&_ul]:space-y-1
          [&_li]:text-gray-400"
        dangerouslySetInnerHTML={{ __html: page.content }}
      />
    </div>
  )
}
